# ---------------------------------------------------------------------------
# Weather module (needed for SPEI, weather inputs and weather forecasts).
# Included as the git submodule external/weather_time_series (git clone --recursive);
# a copy in the parent / a sibling folder or WEATHER_MODULE_DIR is used first if present.
# ---------------------------------------------------------------------------
def _find_weather_module() -> Path:
    cands = [os.environ.get("WEATHER_MODULE_DIR"), ROOT.parent,
             ROOT.parent / "weather_time_series", ROOT.parent / "weather_module",
             ROOT / "external" / "weather_time_series"]          # git submodule
    for c in cands:
        if c and (Path(c) / "src" / "dataprep" / "spei.py").exists():
            return Path(c)
    raise FileNotFoundError(
        "Weather module not found. Run `python src/dataprep/ensure_weather.py` "
        "(fetches the git submodule external/weather_time_series).")


WEATHER_DIR = _find_weather_module()
