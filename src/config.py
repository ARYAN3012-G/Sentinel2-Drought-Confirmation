def weather_module(relpath: str):
    """Load a file of the weather module by path (both repos have packages named
    dataprep/config, so a normal import could pick the wrong one)."""
    import importlib.util
    name = "weather_" + relpath.replace("/", "_").removesuffix(".py")
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, WEATHER_DIR / "src" / relpath)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod

