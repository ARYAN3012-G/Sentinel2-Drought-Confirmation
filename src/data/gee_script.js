Map.centerObject(fields, 9);
Map.addLayer(fields, {color: 'yellow'}, '40 Study Fields');

// 2. Cloud Masking using SCL (Scene Classification Layer)
function maskS2clouds(image) {
  var scl = image.select('SCL');
  // Mask: 3 (shadow), 8 (cloud med), 9 (cloud high), 10 (cirrus), 11 (snow)
  var mask = scl.neq(3).and(scl.neq(8)).and(scl.neq(9)).and(scl.neq(10)).and(scl.neq(11));
  return image.updateMask(mask)
    .select(['B4', 'B8', 'B11'])
    .divide(10000)
    .copyProperties(image, ['system:time_start']);
}

// 3. Compute Spectral Indices
function addIndices(image) {
  var b4 = image.select('B4');
  var b8 = image.select('B8');
  var b11 = image.select('B11');

  // NDVI = (B8 - B4) / (B8 + B4)
  var ndvi = b8.subtract(b4).divide(b8.add(b4)).rename('NDVI');
  
  // NDMI = (B8 - B11) / (B8 + B11)
  var ndmi = b8.subtract(b11).divide(b8.add(b11)).rename('NDMI');
  
  // SAVI = 1.5 * (B8 - B4) / (B8 + B4 + 0.5)
  var savi = b8.subtract(b4).multiply(1.5).divide(b8.add(b4).add(0.5)).rename('SAVI');
  
  // Day of Year (DOY)
  var date = ee.Date(image.get('system:time_start'));
  var doy = ee.Image.constant(date.getRelative('day', 'year')).rename('DOY');
  
  return image.addBands([ndvi, ndmi, savi, doy]);
}

// 4. Query Sentinel-2 Harmonized SR (2020 to 2025)
var s2 = ee.ImageCollection('COPERNICUS/S2_SR_HARMONIZED')
  .filterBounds(fields)
  .filterDate('2020-01-01', '2025-12-31')
  .filter(ee.Filter.lt('CLOUDY_PIXEL_PERCENTAGE', 70))
  .map(maskS2clouds)
  .map(addIndices);

print('Total matching Sentinel-2 scenes:', s2.size());

// 5. Extract Zonal Mean per Parcel
var timeSeries = s2.map(function(img) {
  var date = ee.Date(img.get('system:time_start')).format('YYYY-MM-dd');
  return img.select(['NDVI', 'NDMI', 'SAVI', 'DOY']).reduceRegions({
    collection: fields,
    reducer: ee.Reducer.mean(),
    scale: 10
  }).map(function(f) {
    return f.set('date', date);
  });
}).flatten();

// Filter out scenes where entire polygon was masked/cloudy
var cleanTimeSeries = timeSeries.filter(ee.Filter.notNull(['NDVI', 'NDMI']));

